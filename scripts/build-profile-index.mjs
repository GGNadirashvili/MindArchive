// Generates src/content/registry.ts: a light index of every profile (for the gallery) plus lazy loaders,
// so the full text of a profile is only downloaded when it is opened.
//   node scripts/build-profile-index.mjs      (runs automatically before `npm run build` and `npm run dev`)
import { writeFile } from 'node:fs/promises'
import { loadContentGroups } from './content-modules.mjs'

const groups = await loadContentGroups()
const cards = []
const groupOf = {}
for (const g of groups) {
  for (const p of g.profiles) {
    if (groupOf[p.slug]) throw new Error(`Duplicate profile slug "${p.slug}" in ${g.file} and ${groupOf[p.slug]}`)
    groupOf[p.slug] = g.file
    cards.push({ slug: p.slug, order: p.order, dates: p.dates, place: p.place, era: p.era, tradition: p.tradition, tagline: p.tagline })
  }
}
cards.sort((a, b) => a.order - b.order)

const loaders = groups.map((g) => `  '${g.file}': () => import('./${g.file}').then((m) => m.${g.exportName}),`).join('\n')
const out = `// GENERATED by scripts/build-profile-index.mjs. Do not edit by hand.
import type { Profile } from './types'

export type ProfileCard = Pick<Profile, 'slug' | 'order' | 'dates' | 'place' | 'era' | 'tradition' | 'tagline'>

/** Everything the gallery needs; small enough to ship with the page. */
export const PROFILE_CARDS: ProfileCard[] = ${JSON.stringify(cards, null, 1)}

const GROUP_OF: Record<string, string> = ${JSON.stringify(groupOf, null, 1)}

const LOADERS: Record<string, () => Promise<Profile[]>> = {
${loaders}
}

/** Downloads the group of profiles that holds \`slug\` (about five profiles) and returns the one asked for. */
export async function loadProfile(slug: string): Promise<Profile | undefined> {
  const group = GROUP_OF[slug]
  if (!group) return undefined
  return (await LOADERS[group]()).find((p) => p.slug === slug)
}
`
await writeFile('src/content/registry.ts', out)
console.log(`registry.ts: ${cards.length} profiles in ${groups.length} groups`)
